-- ============================================================
-- 1. certifications 테이블에 grade 컬럼 추가 (없을 때만)
-- ============================================================
SET @col_exists = (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'certifications'
      AND COLUMN_NAME = 'grade'
);

SET @sql = IF(@col_exists = 0,
    'ALTER TABLE certifications ADD COLUMN grade VARCHAR(20) NOT NULL DEFAULT ''기타'' AFTER category',
    'SELECT ''grade column already exists'' AS msg'
);

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

